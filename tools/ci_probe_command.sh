#!/usr/bin/env bash
# ============================================================================
#  clash-source 国内云端探针 —— 流水线执行命令（唯一权威版本）
#
#  ⚠ 为什么单独存一份：流水线的命令与定时器存在**云效自己的数据库里**，
#    不在仓库中。云效文档写明「欠费后立即停机，停机满 15 天释放所有云效
#    组织，研发数据无法找回」—— 组织被删时仓库会一起没，但这段配置
#    只能靠本文件重建。所以它必须与主仓一起版本管理。
#
#  用法：云效 → 流水线 → 编辑 → 执行命令 → 把下面这行粘进去（删掉注释）
#  ⚠ 首条命令必须**自包含**（下面这行就是线上实际在跑的）：
#    云效会复用带缓存的 workspace，而要靠同步才能拿到的脚本，
#    恰恰就是 `bash tools/sync_and_probe.sh` 自己 —— workspace 太旧时它会直接
#    `No such file or directory`（等于自举失败）。所以同步循环必须写进命令本身。
#
#  ⚠ sync_and_probe.sh 内部还会再同步一次（幂等、无害）：
#    它也可能被手动或其它入口直接调用。
# ============================================================================

ok=0; for i in $(seq 1 8); do git fetch origin && git reset --hard origin/master && { ok=1; break; }; sleep 20; done; [ "$ok" = "1" ] && bash tools/sync_and_probe.sh || { echo "同步失败：云效 git 端点抖动，本轮放弃"; exit 1; }
